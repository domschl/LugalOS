#!/usr/bin/env python3
"""Generate MicroPython MICROPY_MODULE_FROZEN_STR table (mpy_frozen_content.c)."""

from __future__ import annotations

import argparse
from pathlib import Path


def c_bytes_literal(data: bytes) -> str:
    lines: list[str] = []
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mpy-dir", required=True)
    ap.add_argument("--frozen-dir", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    mpy_dir = Path(args.mpy_dir)
    frozen_dir = Path(args.frozen_dir)
    out_path = Path(args.out)

    entries: list[tuple[str, bytes]] = []

    asyncio_dir = mpy_dir / "extmod" / "asyncio"
    for p in sorted(asyncio_dir.glob("*.py")):
        if p.name == "uasyncio.py":
            entries.append(("uasyncio.py", p.read_bytes()))
        else:
            entries.append((f"asyncio/{p.name}", p.read_bytes()))

    for p in sorted(frozen_dir.glob("*.py")):
        entries.append((p.name, p.read_bytes()))

    names_blob = b"".join(name.encode("utf-8") + b"\x00" for name, _ in entries) + b"\x00"
    sizes = [len(content) for _, content in entries] + [0]
    content_blob = b"".join(content + b"\x00" for _, content in entries)

    c_code = [
        "/* Auto-generated by tools/gen_mpy_frozen.py. Do not edit. */",
        "#include <stdint.h>",
        "",
        "const char mp_frozen_names[] = {",
        c_bytes_literal(names_blob),
        "};",
        "",
        "const uint32_t mp_frozen_str_sizes[] = {",
        "    " + ", ".join(f"{s}u" for s in sizes),
        "};",
        "",
        "const char mp_frozen_str_content[] = {",
        c_bytes_literal(content_blob),
        "};",
        "",
    ]

    out_path.parent.mkdir(parents=True, exist_ok=True)
    text = "\n".join(c_code)
    if not out_path.exists() or out_path.read_text(encoding="utf-8") != text:
        out_path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
