#!/usr/bin/env python3
"""gen_serif_faces.py - the reader's extra text sizes (77.1, `ui.text_size`).

The reader's own serif sizes are drivers/font_serif.c (16 px) and
drivers/font_noto_serif.c (32 px, tools/gen_noto_fonts.py). This adds the
sizes around them on the boards with flash to spare: 13 and 24 px around the
16 px of the 1x panels, 24 and 40 px around the 32 px of the Tab5.

Each size is rendered exactly as the 32 px face is, scaled: the same font
file, the point size and the vertical offset in proportion (26 pt in a
32 px cell), a space of a quarter of the cell, advances capped at the cell.
Only the 4-bit coverage is stored (two pixels a byte, the left one in the low
nibble, rows of ceil(h / 2) bytes); drivers/ugui.c draws 1-bpp from it at the
32 px face's threshold (coverage >= 6 of 15, its `>= 96` of 255).

Writes drivers/font_serif_faces.c and drivers/include/drivers/font_serif_faces.h.
`--check`: exits 1 when they differ from what would be written.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SERIF_PATHS = [
    "/usr/share/fonts/TTF/GentiumBook-Regular.ttf",
    "/usr/share/fonts/gentium/GentiumBook-Regular.ttf",
    "/usr/share/texmf-dist/fonts/truetype/SIL/gentium-sil/GentiumBook-Regular.ttf",
    "/usr/share/fonts/noto/NotoSerif-Regular.ttf",
    "/usr/share/fonts/truetype/noto/NotoSerif-Regular.ttf",
]

SIZES = [13, 24, 40]
FIRST, LAST = 0x20, 0x7E


def find_font() -> str:
    for p in SERIF_PATHS:
        if Path(p).exists():
            return p
    sys.exit(f"no serif font found in {SERIF_PATHS}")


def render(path: str, h: int) -> tuple[list[int], list[list[list[int]]]]:
    font = ImageFont.truetype(path, round(26 * h / 32))
    dy = -round(h / 32)
    stride = (h + 1) // 2
    widths: list[int] = []
    glyphs: list[list[list[int]]] = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        if code == 0x20:
            widths.append(max(2, round(h / 4)))
            glyphs.append([[0] * stride for _ in range(h)])
            continue
        w = min(h, max(2, int(round(font.getlength(ch)))))
        img = Image.new("L", (stride * 2, h), color=0)
        ImageDraw.Draw(img).text((0, dy), ch, font=font, fill=255)
        rows = []
        for y in range(h):
            row = []
            for b in range(stride):
                p0 = img.getpixel((b * 2, y)) >> 4
                p1 = img.getpixel((b * 2 + 1, y)) >> 4
                row.append((p1 << 4) | p0)
            rows.append(row)
        widths.append(w)
        glyphs.append(rows)
    return widths, glyphs


def emit(sizes: dict[int, tuple[list[int], list[list[list[int]]]]], source: str) -> tuple[str, str]:
    name = Path(source).name
    h = [
        "#ifndef LUGALOS_DRIVERS_FONT_SERIF_FACES_H",
        "#define LUGALOS_DRIVERS_FONT_SERIF_FACES_H",
        "",
        "#include <stdint.h>",
        "",
        f"/* The reader's extra serif sizes, generated by tools/gen_serif_faces.py from {name};",
        " * do not edit. Glyphs 0x20..0x7E: an advance each, and 4-bit coverage rows of",
        " * ceil(h / 2) bytes (the left pixel in the low nibble). Only where",
        " * UGUI_TEXT_SIZES is defined (drivers/ugui.h). */",
        "",
        "#define FONT_SERIF_FACES_FIRST 0x20",
        "#define FONT_SERIF_FACES_COUNT 95",
        "",
    ]
    c = [
        f"/* drivers/font_serif_faces.c -- generated by tools/gen_serif_faces.py from {name};",
        " * do not edit. */",
        "",
        '#include "drivers/font_serif_faces.h"',
        '#include "drivers/ugui.h"',
        "",
        "#if defined(UGUI_TEXT_SIZES)",
        "",
    ]
    for size, (widths, glyphs) in sizes.items():
        stride = (size + 1) // 2
        h.append(f"extern const uint8_t font_serif{size}_widths[FONT_SERIF_FACES_COUNT];")
        h.append(f"extern const uint8_t font_serif{size}_aa[FONT_SERIF_FACES_COUNT][{size}][{stride}];")
        c.append(f"const uint8_t font_serif{size}_widths[FONT_SERIF_FACES_COUNT] = {{")
        for i in range(0, len(widths), 16):
            c.append("    " + ", ".join(str(w) for w in widths[i:i + 16]) + ",")
        c.append("};")
        c.append("")
        c.append(f"const uint8_t font_serif{size}_aa[FONT_SERIF_FACES_COUNT][{size}][{stride}] = {{")
        for gi, rows in enumerate(glyphs):
            c.append(f"    {{   /* {chr(FIRST + gi)!r} */")
            for row in rows:
                c.append("        { " + ", ".join(f"0x{b:02x}" for b in row) + " },")
            c.append("    },")
        c.append("};")
        c.append("")
    h += ["", "#endif /* LUGALOS_DRIVERS_FONT_SERIF_FACES_H */", ""]
    c += ["#endif", ""]
    return "\n".join(h), "\n".join(c)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the files would change")
    args = ap.parse_args()
    root = Path(__file__).resolve().parent.parent
    source = find_font()
    header, body = emit({s: render(source, s) for s in SIZES}, source)
    out_h = root / "drivers/include/drivers/font_serif_faces.h"
    out_c = root / "drivers/font_serif_faces.c"
    if args.check:
        same = out_h.exists() and out_c.exists() and out_h.read_text() == header and out_c.read_text() == body
        print(f"gen_serif_faces: {'matches' if same else 'DIFFERS from'} {source}")
        return 0 if same else 1
    out_h.write_text(header)
    out_c.write_text(body)
    print(f"gen_serif_faces: sizes {SIZES} from {source} -> {out_c.relative_to(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
