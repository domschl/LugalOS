def generate_c() -> str:
    # Sort glyphs by codepoint
    sorted_glyphs = sorted(GLYPHS, key=lambda g: g[0])

    out = [
        '/* drivers/font_math.c — Mathematical Font Glyphs & Metrics for LugalOS.',
        ' * Freestanding Flash .rodata tables for Knuth Appendix G math typesetting. */',
        '',
        '#include "drivers/font_math.h"',
        '#include "drivers/font_serif.h"',
        '#include <stddef.h>',
        '',
    ]

    # Emit bitmap arrays
    for cp, name, w, h, bx, by, adv, rows in sorted_glyphs:
        row_strs = ", ".join(f"0x{r:04x}" for r in rows)
        out.append(f'static const uint16_t glyph_data_{name}[] = {{ {row_strs} }};')

    out.append('')
    out.append('/* Flash .rodata table sorted by codepoint for O(log N) bsearch */')
    out.append('static const math_glyph_t g_math_glyphs[] = {')

    for cp, name, w, h, bx, by, adv, rows in sorted_glyphs:
        out.append(f'    {{ 0x{cp:04x}, {w}, {h}, {bx}, {by}, {adv}, glyph_data_{name} }},')

    out.append('};')
    out.append(f'#define MATH_GLYPH_COUNT {len(sorted_glyphs)}')
    out.append('')

    out.append('''const math_glyph_t *font_math_lookup(uint16_t codepoint, math_style_t style) {
    (void)style;
    int lo = 0;
    int hi = MATH_GLYPH_COUNT - 1;

    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (g_math_glyphs[mid].codepoint == codepoint) {
            return &g_math_glyphs[mid];
        }
        if (g_math_glyphs[mid].codepoint < codepoint) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return NULL;
}

int font_math_axis_height(math_style_t style) {
    switch (style) {
    case STYLE_DISPLAY:
    case STYLE_TEXT:         return 6;   /* 6 px above baseline */
    case STYLE_SCRIPT:       return 4;
    case STYLE_SCRIPTSCRIPT: return 3;
    default:                 return 6;
    }
}

int font_math_rule_thickness(math_style_t style) {
    (void)style;
    return 1;
}

int font_math_quad(math_style_t style) {
    switch (style) {
    case STYLE_DISPLAY:
    case STYLE_TEXT:         return 16;
    case STYLE_SCRIPT:       return 11;
    case STYLE_SCRIPTSCRIPT: return 8;
    default:                 return 16;
    }
}

bool font_math_get_delim_pieces(math_delim_t delim, math_delim_pieces_t *pieces) {
    if (!pieces) return false;
    (void)delim;
    return false;
}
''')
    return "\n".join(out)

def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    out_file = repo_root / "drivers" / "font_math.c"
    content = generate_c()
    out_file.write_text(content, encoding="utf-8")
    print(f"Generated {out_file} ({len(content)} bytes)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
