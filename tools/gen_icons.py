#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pillow"]
# ///
"""gen_icons.py - the built-in icons from assets/icons/*.png.

Each PNG (any mode, any size; drawn for 64 x 64, see tools/draw_icons.py)
becomes a 64 x 64 and a 32 x 32 image of 4-bit gray: 0 ink .. 14 white, 15
transparent (alpha under half). The 32 x 32 one is the 64 x 64 one's 2 x 2
averages, so art drawn with 2-pixel strokes on even coordinates stays crisp.

Emits drivers/icons_data.c: the images in .rodata, sorted by name for the
kernel's binary search (drivers/icons.c). With --gic DIR also each as
NAME.GIC (64 x 64; the format in drivers/include/drivers/icons.h), the form an
icon takes on the SD card (/sd0/system/icons/). --check compares instead of
writing, for the test suite.

Usage: uv run tools/gen_icons.py [--check] [--gic DIR]
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "icons"
OUT = ROOT / "drivers" / "icons_data.c"
TRANSPARENT = 15


def load64(path: Path) -> list[list[int]]:
    """The icon as 64 x 64 levels 0..14, 15 transparent."""
    im = Image.open(path).convert("LA")
    if im.size != (64, 64):
        im = im.resize((64, 64), Image.Resampling.LANCZOS)
    rows: list[list[int]] = []
    for y in range(64):
        row: list[int] = []
        for x in range(64):
            gray, alpha = im.getpixel((x, y))  # type: ignore[misc]
            row.append(TRANSPARENT if alpha < 128 else round(gray * 14 / 255))
        rows.append(row)
    return rows


def half(px: list[list[int]]) -> list[list[int]]:
    """2 x 2 averages of the opaque pixels; transparent where most were."""
    n = len(px) // 2
    out: list[list[int]] = []
    for y in range(n):
        row: list[int] = []
        for x in range(n):
            q = [px[2 * y + a][2 * x + b] for a in (0, 1) for b in (0, 1)]
            opaque = [v for v in q if v != TRANSPARENT]
            row.append(TRANSPARENT if len(opaque) < 2 else round(sum(opaque) / len(opaque)))
        out.append(row)
    return out


def pack(px: list[list[int]]) -> bytes:
    """Two pixels a byte, the left one in the high nibble; rows padded to a byte."""
    out = bytearray()
    for row in px:
        for x in range(0, len(row), 2):
            hi = row[x]
            lo = row[x + 1] if x + 1 < len(row) else TRANSPARENT
            out.append((hi << 4) | lo)
    return bytes(out)


def gic(px: list[list[int]]) -> bytes:
    h, w = len(px), len(px[0])
    return b"GIC1" + struct.pack("<HHB3x", w, h, 4) + pack(px)


def c_ident(name: str) -> str:
    return "k_icon_" + "".join(ch if ch.isalnum() else "_" for ch in name)


def c_bytes(data: bytes) -> str:
    lines = []
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return "\n".join(lines)


def render(icons: dict[str, list[list[int]]]) -> str:
    out = [
        "/* drivers/icons_data.c -- generated by tools/gen_icons.py from the PNGs in assets/icons/;",
        " * do not edit. The built-in icons, 4-bit gray (0 ink .. 14 white, 15 clear),",
        " * two pixels a byte, sorted by name (drivers/icons.c searches them). */",
        "",
        '#include "drivers/icons.h"',
        "",
    ]
    for name, px in icons.items():
        ident = c_ident(name)
        out.append(f"static const uint8_t {ident}_64[2048] = {{\n{c_bytes(pack(px))}\n}};")
        out.append(f"static const uint8_t {ident}_32[512] = {{\n{c_bytes(pack(half(px)))}\n}};")
        out.append("")
    out.append("const icon_t k_icons[] = {")
    for name in icons:
        ident = c_ident(name)
        out.append(f'    {{ "{name}", {ident}_32, {ident}_64 }},')
    out.append("};")
    out.append("")
    out.append("const unsigned k_icon_count = sizeof(k_icons) / sizeof(k_icons[0]);")
    out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="compare drivers/icons_data.c with the PNGs; write nothing")
    ap.add_argument("--gic", type=Path, help="also write each icon as NAME.GIC (64 x 64) here")
    args = ap.parse_args()
    names = sorted(p.stem for p in SRC.glob("*.png"))      # byte order: strcmp's
    icons = {n: load64(SRC / f"{n}.png") for n in names}
    text = render(icons)
    if args.check:
        same = OUT.exists() and OUT.read_text() == text
        print(f"gen_icons: {OUT.relative_to(ROOT)} {'matches' if same else 'DIFFERS from'} assets/icons/")
        return 0 if same else 1
    OUT.write_text(text)
    if args.gic:
        args.gic.mkdir(parents=True, exist_ok=True)
        for n, px in icons.items():
            (args.gic / f"{n.upper()}.GIC").write_bytes(gic(px))
    print(f"gen_icons: {len(icons)} icons -> {OUT.relative_to(ROOT)} ({len(icons) * 2560} bytes of images)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
