#define MATH_GLYPH_COUNT 40

const math_glyph_t *font_math_lookup(uint16_t codepoint, math_style_t style) {
    (void)style;
    int lo = 0;
    int hi = MATH_GLYPH_COUNT - 1;

    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (g_math_glyphs[mid].codepoint == codepoint) {
            return &g_math_glyphs[mid];
        }
        if (g_math_glyphs[mid].codepoint < codepoint) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return NULL;
}

int font_math_axis_height(math_style_t style) {
    switch (style) {
    case STYLE_DISPLAY:
    case STYLE_TEXT:         return 6;   /* 6 px above baseline */
    case STYLE_SCRIPT:       return 4;
    case STYLE_SCRIPTSCRIPT: return 3;
    default:                 return 6;
    }
}

int font_math_rule_thickness(math_style_t style) {
    (void)style;
    return 1;
}

int font_math_quad(math_style_t style) {
    switch (style) {
    case STYLE_DISPLAY:
    case STYLE_TEXT:         return 16;
    case STYLE_SCRIPT:       return 11;
    case STYLE_SCRIPTSCRIPT: return 8;
    default:                 return 16;
    }
}

bool font_math_get_delim_pieces(math_delim_t delim, math_delim_pieces_t *pieces) {
    if (!pieces) return false;
    (void)delim;
    return false;
}
